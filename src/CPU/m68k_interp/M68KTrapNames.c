static const char* Find(const TrapName* t, int n, UInt16 key, UInt16 mask) {
    for (int i = 0; i < n; i++)
        if ((t[i].trap & mask) == key) return t[i].name;
    return NULL;
}

const char* M68K_TrapName(UInt16 trapWord) {
    if ((trapWord & 0xF000) != 0xA000) return NULL;
    if (trapWord & 0x0800) {
        return Find(kToolboxTraps, (int)(sizeof(kToolboxTraps) / sizeof(kToolboxTraps[0])),
                    trapWord & 0x03FF, 0x03FF);
    }
    return Find(kOSTraps, (int)(sizeof(kOSTraps) / sizeof(kOSTraps[0])),
                trapWord & 0x00FF, 0x00FF);
}
